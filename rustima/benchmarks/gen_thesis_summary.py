"""Generate a master summary table + index of all E1–E14 results.

Produces:
- paper/thesis_results/SUMMARY.md (human-readable index)
- paper/thesis_results/tables/master_summary.tex (one-line-per-experiment)
"""
from __future__ import annotations

import csv
from pathlib import Path

from thesis_utils import PAPER_ROOT, RAW_DIR, TABLES_DIR, FIGURES_DIR


EXPERIMENTS = [
    ("E01", "Likelihood equivalence vs statsmodels", "e01_equivalence.csv", "e01_equivalence.tex", None),
    ("E02", "Sparsity matrix", "e02_sparsity.csv", "e02_sparsity.tex", None),
    ("E03", "KF runtime breakdown", "e03_kf_runtime.csv", None, "e03_kf_runtime.png"),
    ("E04", "Joseph form numerical stability", "e04_joseph.csv", None, None),
    ("E05", "Steady-state convergence stats", "e05_steady_state.csv", None, "e05_steady_state_hist.png"),
    ("E06", "Init path selection", "e06_init_path.csv", "e06_init_path.tex", None),
    ("E07", "Analytical score vs FD", "e07_score.csv", "e07_score.tex", "e07_score_time.png"),
    ("E08", "OPG vs Hessian SE", "e08_opg.csv", "e08_opg.tex", None),
    ("E09", "Warm-start ablation", "e09_warm_start.csv", "e09_warm_start.tex", None),
    ("E10", "PTR vs joint MLE ★", "e10_ptr_summary.csv", "e10_ptr_summary.tex", "e10_ptr_convergence.png"),
    ("E11", "Near-cancellation filtering", "e11_near_cancellation.csv", "e11_near_cancellation.tex", None),
    ("E12", "Stepwise vs Rayon grid auto_arima", "e12_auto_arima.csv", "e12_auto_arima.tex", None),
    ("E13", "Batch memory model", "e13_batch_memory.csv", "e13_batch_memory.tex", "e13_batch_memory.png"),
    ("E14", "Electricity demand case study ★", "e14_power_case.csv", "e14_power_case.tex", "e14_forecast.png"),
]


def file_status(root: Path, name: str | None) -> str:
    if name is None:
        return "—"
    p = root / name
    if p.exists():
        size = p.stat().st_size
        return f"✓ ({size // 1024} KB)" if size > 1024 else f"✓ ({size} B)"
    return "✗ missing"


def main():
    lines = ["# rustima Thesis Experiments — Result Index\n"]
    lines.append("> Generated by `gen_thesis_summary.py`\n")
    lines.append("\n## Experiment Status\n")
    lines.append("| ID | Title | CSV | LaTeX | Figure |\n")
    lines.append("|---|---|---|---|---|\n")
    for eid, title, csv_name, tex_name, fig_name in EXPERIMENTS:
        csv_st = file_status(RAW_DIR, csv_name)
        tex_st = file_status(TABLES_DIR, tex_name)
        fig_st = file_status(FIGURES_DIR, fig_name)
        lines.append(f"| {eid} | {title} | {csv_st} | {tex_st} | {fig_st} |\n")

    # Inline-display key numbers
    lines.append("\n\n## Key Headline Numbers\n\n")

    def safe_read(name: str) -> list[list[str]]:
        p = RAW_DIR / name
        if not p.exists():
            return []
        with open(p) as f:
            return list(csv.reader(f))

    rows = safe_read("e01_equivalence.csv")
    if rows:
        lines.append("### E1 — Likelihood equivalence vs statsmodels\n\n")
        for r in rows:
            lines.append(f"- `{r[0]}`: |ΔLL|_med = `{r[1]}`, speedup = **{r[5]}**×\n")

    rows = safe_read("e10_ptr_summary.csv")
    if rows and len(rows) > 1:
        lines.append("\n### E10 — PTR vs joint MLE (★ headline)\n\n")
        for r in rows[1:]:
            lines.append(f"- **{r[0]}**: convergence `{r[1]}`, LL median `{r[2]}`, β-MSE median `{r[3]}`, iters `{r[4]}`, time `{r[5]}`ms\n")

    rows = safe_read("e14_power_case.csv")
    if rows and len(rows) > 1:
        lines.append("\n### E14 — Electricity demand case study (★)\n\n")
        for r in rows[1:]:
            lines.append(f"- **{r[0]}**: LL=`{r[1]}`, AIC=`{r[2]}`, iter=`{r[3]}`, time=`{r[4]}`ms, RMSE=`{r[5]}`\n")

    rows = safe_read("e13_batch_memory.csv")
    if rows and len(rows) > 1:
        lines.append("\n### E13 — Batch memory model\n\n")
        for r in rows[1:]:
            lines.append(f"- N={r[0]} (n={r[1]}): peak RSS = `{r[3]}` MB, Δ = `{r[4]}` MB ({r[5]} ok)\n")

    rows = safe_read("e02_sparsity.csv")
    if rows and len(rows) > 1:
        lines.append("\n### E2 — State-space sparsity (selected)\n\n")
        for r in rows[1:]:
            if "_24" in r[0] or "_12" in r[0]:
                lines.append(f"- `{r[0]}`: k={r[1]}, density={r[5]}%\n")

    rows = safe_read("e09_warm_start.csv")
    if rows and len(rows) > 1:
        lines.append("\n### E9 — Optimization method comparison\n\n")
        for r in rows[1:]:
            lines.append(f"- **{r[0]}**: convergence `{r[1]}`, iter med `{r[2]}`, time `{r[3]}`ms, LL med `{r[4]}`\n")

    out = PAPER_ROOT / "SUMMARY.md"
    out.write_text("".join(lines))
    print(f"Summary index saved to: {out}")
    print(f"\nLaTeX tables in: {TABLES_DIR}")
    print(f"Figures in: {FIGURES_DIR}")
    print(f"Raw CSV in: {RAW_DIR}")


if __name__ == "__main__":
    main()
